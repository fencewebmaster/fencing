    function coerceValue(path, el) {
        if (el.type === 'checkbox') {
            return el.checked;
        }
        // Choices / Swatches per row: a number in the fence file, as the planner reads it.
        if (/(^|\.)(color_)?columns$/.test(path)) {
            return Number(el.value) || 3;
        }
        if (el.type === 'number') {
            if (el.value === '') {
                return '';
            }
            var n = Number(el.value);
            return Number.isNaN(n) ? el.value : n;
        }
        if (path === 'panel_count' || path.indexOf('pack_qty.') === 0) {
            if (el.value === '') {
                return '';
            }
            var num = Number(el.value);
            return Number.isNaN(num) ? el.value : num;
        }
        return el.value;
    }

