    function renderFieldGroup(title, bodyHtml, opts) {
        opts = opts || {};
        var classes = ['fc-fs-field-group'];
        if (opts.nested) {
            classes.push('fc-fs-field-group--nested');
        }
        if (opts.full !== false) {
            classes.push('fc-fs-field-group--full');
        }
        if (opts.sectionClass) {
            classes.push(opts.sectionClass);
        }
        var gridClass = opts.compact !== false ? ' fc-fs-form-grid--compact' : '';
        var bodyClasses = 'fc-fs-field-group__body fc-fs-form-grid' + gridClass;
        if (opts.bodyClass) {
            bodyClasses += ' ' + opts.bodyClass;
        }
        var hintHtml = opts.hint
            ? '<p class="fc-fs-gui-field__hint">' + escapeHtml(opts.hint) + '</p>'
            : '';
        return (
            '<section class="' +
            classes.join(' ') +
            '">' +
            '<h4 class="fc-fs-field-group__title">' +
            escapeHtml(title) +
            '</h4>' +
            '<div class="' +
            bodyClasses +
            '">' +
            hintHtml +
            bodyHtml +
            '</div></section>'
        );
    }

