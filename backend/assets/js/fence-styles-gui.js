    function filterColorPickerChips(wrap) {
        if (!wrap) {
            return;
        }
        var searchInput = wrap.querySelector('[data-gui-color-search]');
        var pickerEl = wrap.querySelector('[data-gui-color-picker]');
        var emptyEl = wrap.querySelector('[data-gui-color-search-empty]');
        if (!pickerEl) {
            return;
        }
        var query = searchInput ? String(searchInput.value || '').trim().toLowerCase() : '';
        var visible = 0;
        pickerEl.querySelectorAll('[data-gui-color-pick]').forEach(function (chip) {
            var text = chip.getAttribute('data-gui-color-search-text') || '';
            var match = !query || text.indexOf(query) !== -1;
            chip.classList.toggle('is-hidden', !match);
            if (match) {
                visible += 1;
            }
        });
        if (emptyEl) {
            emptyEl.classList.toggle('hidden', visible > 0 || !pickerEl.querySelector('[data-gui-color-pick]'));
        }
    }

