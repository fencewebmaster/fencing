    function objectFromKvTableOrder(block, oldObj) {
        oldObj = isPlainObject(oldObj) ? oldObj : {};
        var table = block ? block.querySelector('.fc-fs-kv-table') : null;
        if (!table) {
            return oldObj;
        }
        var newObj = {};
        table.querySelectorAll('.fc-fs-kv-row[data-gui-kv-key]').forEach(function (row) {
            var key = row.getAttribute('data-gui-kv-key');
            if (key !== null && Object.prototype.hasOwnProperty.call(oldObj, key)) {
                newObj[key] = oldObj[key];
            }
        });
        Object.keys(oldObj).forEach(function (key) {
            if (!Object.prototype.hasOwnProperty.call(newObj, key)) {
                newObj[key] = oldObj[key];
            }
        });
        return newObj;
    }

    function syncSlatRowsOrderFromDom(wrap, basePath, state, helpers, applyPath) {
        if (!wrap || !basePath) {
            return;
        }
        var table = wrap.querySelector('.fc-fs-kv-table');
        var rows = helpers.getByPath(state.config, basePath) || [];
        if (!table || !Array.isArray(rows)) {
            return;
        }
        var domRows = table.querySelectorAll('.fc-fs-kv-row[data-gui-slat-row-idx]');
        var nextRows = [];
        domRows.forEach(function (row) {
            var idx = parseInt(row.getAttribute('data-gui-slat-row-idx'), 10);
            if (!Number.isNaN(idx) && rows[idx]) {
                nextRows.push(rows[idx]);
            }
        });
        if (nextRows.length !== rows.length) {
            return;
        }
        applyPath(basePath, nextRows);
        rerenderSlatRows(wrap, basePath, nextRows);
    }

    function bindColorSelectedDragDrop(guiRoot, state, helpers, applyPath) {
        var dragRow = null;

        function clearDragOver() {
            guiRoot.querySelectorAll('.fc-fs-color-selected-row--drag-over').forEach(function (row) {
                row.classList.remove('fc-fs-color-selected-row--drag-over');
            });
        }

        function resetDraggable() {
            guiRoot.querySelectorAll('[data-gui-color-row]').forEach(function (row) {
                row.draggable = false;
            });
        }

        function moveColorRowBeforeTarget(fromRow, targetRow) {
            if (!fromRow || !targetRow || fromRow === targetRow) {
                return;
            }
            var parent = targetRow.parentNode;
            if (!parent) {
                return;
            }
            var siblings = Array.prototype.slice.call(parent.querySelectorAll(':scope > [data-gui-color-row]'));
            var fromIndex = siblings.indexOf(fromRow);
            var toIndex = siblings.indexOf(targetRow);
            if (fromIndex < 0 || toIndex < 0) {
                return;
            }
            if (fromIndex < toIndex) {
                parent.insertBefore(fromRow, targetRow.nextSibling);
            } else {
                parent.insertBefore(fromRow, targetRow);
            }
        }

        function syncColorOrderFromDom(wrap) {
            if (!wrap) {
                return;
            }
            var path = wrap.getAttribute('data-gui-colors');
            var list = wrap.querySelector('[data-gui-color-selected]');
            if (!path || !list) {
                return;
            }
            var slugs = [];
            list.querySelectorAll('[data-gui-color-row]').forEach(function (row) {
                var slug = row.getAttribute('data-gui-color-slug');
                if (slug) {
                    slugs.push(slug);
                }
            });
            applyPath(path, slugs);
            updateColorSectionDom(wrap, slugs, state);
        }

        guiRoot.addEventListener('mousedown', function (e) {
            var grip = e.target.closest('[data-gui-color-grip]');
            if (!grip || !guiRoot.contains(grip)) {
                return;
            }
            var row = grip.closest('[data-gui-color-row]');
            if (row) {
                row.draggable = true;
            }
        });

        guiRoot.addEventListener('mouseup', resetDraggable);

        guiRoot.addEventListener('dragstart', function (e) {
            var row = e.target.closest('[data-gui-color-row]');
            if (!row || !guiRoot.contains(row) || !row.draggable) {
                return;
            }
            dragRow = row;
            row.classList.add('fc-fs-color-selected-row--dragging');
            if (e.dataTransfer) {
                e.dataTransfer.effectAllowed = 'move';
                e.dataTransfer.setData('text/plain', 'color-row');
            }
        });

        guiRoot.addEventListener('dragend', function () {
            if (dragRow) {
                dragRow.classList.remove('fc-fs-color-selected-row--dragging');
            }
            clearDragOver();
            resetDraggable();
            dragRow = null;
        });

        guiRoot.addEventListener('dragover', function (e) {
            if (!dragRow) {
                return;
            }
            var list = dragRow.closest('[data-gui-color-selected]');
            var target = e.target.closest('[data-gui-color-row]');
            if (!list || !target || target.closest('[data-gui-color-selected]') !== list || target === dragRow) {
                return;
            }
            e.preventDefault();
            target.classList.add('fc-fs-color-selected-row--drag-over');
        });

        guiRoot.addEventListener('dragleave', function (e) {
            var row = e.target.closest('[data-gui-color-row]');
            if (row) {
                row.classList.remove('fc-fs-color-selected-row--drag-over');
            }
        });

        guiRoot.addEventListener('drop', function (e) {
            if (!dragRow) {
                return;
            }
            var list = dragRow.closest('[data-gui-color-selected]');
            var target = e.target.closest('[data-gui-color-row]');
            if (!list || !target || target.closest('[data-gui-color-selected]') !== list || target === dragRow) {
                return;
            }
            e.preventDefault();
            moveColorRowBeforeTarget(dragRow, target);
            clearDragOver();
            syncColorOrderFromDom(list.closest('[data-gui-colors]'));
        });
    }

