    function renderGuiField(label, path, value, opts) {
        opts = opts || {};
        var id = opts.id || uid('fc-gui');
        var type = opts.type || 'text';
        var span = opts.span ? ' fc-fs-gui-field--span' : '';
        var mono = opts.mono ? ' fc-fs-input--mono' : '';
        var readonly = opts.readonly ? ' readonly' : '';
        var hint = opts.hint
            ? '<span class="fc-fs-gui-field__hint">' + escapeHtml(opts.hint) + '</span>'
            : '';

        if (type === 'checkbox') {
            return (
                '<label class="fc-fs-gui-toggle' +
                span +
                '">' +
                '<input type="checkbox" id="' +
                id +
                '" data-gui-path="' +
                escapeHtml(path) +
                '"' +
                (value ? ' checked' : '') +
                ' class="fc-fs-gui-toggle__input">' +
                '<span class="fc-fs-gui-toggle__track" aria-hidden="true"></span>' +
                '<span class="fc-fs-gui-toggle__label">' +
                escapeHtml(label) +
                '</span></label>'
            );
        }

        if (type === 'textarea') {
            return (
                '<label class="fc-fs-gui-field' +
                span +
                '">' +
                '<span class="fc-fs-gui-field__label">' +
                escapeHtml(label) +
                '</span>' +
                hint +
                '<textarea id="' +
                id +
                '" data-gui-path="' +
                escapeHtml(path) +
                '" rows="' +
                (opts.rows || 3) +
                '" class="fc-fs-input' +
                mono +
                '">' +
                escapeHtml(value == null ? '' : String(value)) +
                '</textarea></label>'
            );
        }

        if (type === 'html') {
            var rawValue =
                global.FcFenceStyleWysiwyg &&
                typeof global.FcFenceStyleWysiwyg.serializeTextareaValue === 'function'
                    ? global.FcFenceStyleWysiwyg.serializeTextareaValue(value)
                    : String(value == null ? '' : value);
            return (
                '<div class="fc-fs-gui-field fc-fs-gui-field--wysiwyg' +
                span +
                '">' +
                '<span class="fc-fs-gui-field__label">' +
                escapeHtml(label) +
                '</span>' +
                hint +
                '<textarea id="' +
                id +
                '" data-gui-path="' +
                escapeHtml(path) +
                '" data-fc-wysiwyg="1" rows="' +
                (opts.rows || 6) +
                '" class="fc-fs-input fc-fs-wysiwyg">' +
                rawValue +
                '</textarea></div>'
            );
        }

        if (type === 'image') {
            return renderGuiImageField(label, path, value, opts);
        }

        return (
            '<label class="fc-fs-gui-field' +
            span +
            '">' +
            '<span class="fc-fs-gui-field__label">' +
            escapeHtml(label) +
            '</span>' +
            hint +
            '<input type="' +
            type +
            '" id="' +
            id +
            '" data-gui-path="' +
            escapeHtml(path) +
            '" value="' +
            escapeHtml(value == null ? '' : String(value)) +
            '"' +
            readonly +
            ' class="fc-fs-input' +
            mono +
            (opts.readonly ? ' fc-fs-input--readonly' : '') +
            '"></label>'
        );
    }

