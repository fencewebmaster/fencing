    function confirmDelete(title, message) {
        var Modal = global.FcAdminModal;
        if (Modal && typeof Modal.confirm === 'function') {
            return Modal.confirm({
                title: title || 'Delete',
                message: message || 'Remove this item?',
                confirmLabel: 'Delete',
                cancelLabel: 'Cancel',
                variant: 'warning'
            });
        }
        return Promise.resolve(global.confirm(message || title || 'Delete this item?'));
    }

    function itemLabelText(label, fallback) {
        var text = String(label == null ? '' : label).trim();
        if (text) {
            return text;
        }
        text = String(fallback == null ? '' : fallback).trim();
        return text || 'Untitled';
    }

    function confirmDeleteItem(title, itemLabel) {
        return confirmDelete(title, 'Remove “' + itemLabelText(itemLabel) + '”?');
    }

    function confirmDeleteIfNeeded(title, itemLabel, isEmpty) {
        if (isEmpty) {
            return Promise.resolve(true);
        }
        return confirmDeleteItem(title, itemLabel);
    }

    function isAutoGeneratedKey(key, prefix) {
        return new RegExp('^' + prefix + '_\\d+$').test(String(key));
    }

    function kvKeyInputValue(key, basePath) {
        var prefix = basePath === 'pack_qty' ? 'sku' : 'option';
        if (isAutoGeneratedKey(key, prefix)) {
            return '';
        }
        return String(key);
    }

    function isKvRowEmpty(kvRow, kvBase, removeKey, helpers, state) {
        var keyInput = kvRow.querySelector('[data-gui-kv-key-input]');
        var key = keyInput ? keyInput.value.trim() : String(removeKey);

        if (kvBase === 'pack_qty') {
            var qtyInput = kvRow.querySelector('[data-gui-path="' + kvBase + '.' + removeKey + '"]');
            var qty = qtyInput ? qtyInput.value : helpers.getByPath(state.config, kvBase + '.' + removeKey);
            return isAutoGeneratedKey(key, 'sku') && (qty === 1 || qty === '1');
        }

        var labelInput = kvRow.querySelector('[data-gui-path="' + kvBase + '.' + removeKey + '"]');
        var kvObj = helpers.getByPath(state.config, kvBase) || {};
        var label = labelInput
            ? labelInput.value.trim()
            : String(kvObj[removeKey] != null ? kvObj[removeKey] : '').trim();
        var untouchedLabel = !label;
        var untouchedKey = !key || isAutoGeneratedKey(key, 'option');
        return untouchedLabel && untouchedKey;
    }

    function isSlatRowEmpty(slatRowEl, slatRowsPath, slatIdx, helpers, state) {
        var valueInput = slatRowEl.querySelector(
            '[data-gui-path="' + slatRowsPath + '.' + slatIdx + '.value"]'
        );
        var labelInput = slatRowEl.querySelector(
            '[data-gui-path="' + slatRowsPath + '.' + slatIdx + '.label"]'
        );
        var value = valueInput ? valueInput.value.trim() : '';
        var label = labelInput ? labelInput.value.trim() : '';
        if (!value && !label) {
            return true;
        }
        var row = (helpers.getByPath(state.config, slatRowsPath) || [])[slatIdx] || {};
        value = value || String(row.value != null ? row.value : '').trim();
        label = label || String(row.label || '').trim();
        return !value && !label;
    }

    function isOptionCardEmpty(card, helpers, state) {
        var path = card.getAttribute('data-gui-option-path');
        var idx = parseInt(card.getAttribute('data-gui-option-idx'), 10);
        var slugInput = card.querySelector('[data-gui-path="' + path + '.' + idx + '.slug"]');
        var titleInput = card.querySelector('[data-gui-path="' + path + '.' + idx + '.title"]');
        var slug = slugInput ? slugInput.value.trim() : '';
        var title = titleInput ? titleInput.value.trim() : '';
        if (!slug && !title) {
            return true;
        }
        var opt = (helpers.getByPath(state.config, path) || [])[idx] || {};
        slug = slug || String(opt.slug || '').trim();
        title = title || String(opt.title || '').trim();
        return !slug && !title;
    }

    function optionCardDeleteLabel(card, helpers, state) {
        var path = card.getAttribute('data-gui-option-path');
        var idx = parseInt(card.getAttribute('data-gui-option-idx'), 10);
        var titleInput = card.querySelector('[data-gui-path="' + path + '.' + idx + '.title"]');
        if (titleInput && titleInput.value.trim()) {
            return titleInput.value.trim();
        }
        var opt = (helpers.getByPath(state.config, path) || [])[idx] || {};
        return itemLabelText(opt.title, opt.slug);
    }

    function kvRowDeleteLabel(kvRow, kvBase, removeKey, helpers, state) {
        if (kvBase === 'pack_qty') {
            var qty = helpers.getByPath(state.config, kvBase + '.' + removeKey);
            return itemLabelText(removeKey + ' (' + qty + ' per pack)', removeKey);
        }
        var labelInput = kvRow.querySelector('[data-gui-path="' + kvBase + '.' + removeKey + '"]');
        if (labelInput && labelInput.value.trim()) {
            return labelInput.value.trim();
        }
        var obj = helpers.getByPath(state.config, kvBase) || {};
        return itemLabelText(obj[removeKey], removeKey);
    }

    function slatRowDeleteLabel(slatRowEl, slatRowsPath, slatIdx, helpers, state) {
        var labelInput = slatRowEl.querySelector('[data-gui-path="' + slatRowsPath + '.' + slatIdx + '.label"]');
        if (labelInput && labelInput.value.trim()) {
            return labelInput.value.trim();
        }
        var rows = helpers.getByPath(state.config, slatRowsPath) || [];
        var row = rows[slatIdx] || {};
        return itemLabelText(row.label, row.value);
    }

