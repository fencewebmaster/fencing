    function syncGuiNavTabUi(scope, options) {
        options = options || {};
        var guiTab = options.guiTab || 'overview';

        var editRoot =
            (scope && scope.closest && scope.closest('.fc-admin-fence-style-edit')) ||
            scope ||
            document;

        editRoot.querySelectorAll('[data-gui-tab][role="tab"]').forEach(function (btn) {
            var active = btn.getAttribute('data-gui-tab') === guiTab;
            btn.setAttribute('aria-selected', active ? 'true' : 'false');
            btn.classList.toggle('is-active', active);
            btn.classList.toggle('bg-white', active);
            btn.classList.toggle('text-slate-900', active);
            btn.classList.toggle('shadow-sm', active);
            btn.classList.toggle('text-slate-600', !active);
        });

        var guiRoot = editRoot.querySelector('.fc-fs-gui-mode');
        if (guiRoot && guiTab !== 'advanced') {
            guiRoot.querySelectorAll('[data-gui-panel]').forEach(function (panel) {
                panel.classList.toggle('hidden', panel.getAttribute('data-gui-panel') !== guiTab);
            });
        }
    }

